//! Compares every method with what V8 answers, recorded by `tests/fixtures/gen.mjs` in `js_parity.json`.
//!
//! A pattern without the `u` or `v` flag may only differ on a text holding a character outside the basic
//! multilingual plane, the known difference documented on `Regex`; such differences are counted, not failed.

use std::collections::BTreeMap;

use fastjs_regex::{Match, Regex, byte_index, utf16_index};
use serde_json::{Map, Value, json};

const SURROGATE: &str = "surrogate";

#[derive(Default)]
struct Tally {
    checks: BTreeMap<&'static str, usize>,
    astral_differences: usize,
    surrogate_skips: usize,
    failures: Vec<String>,
}

struct Case<'p> {
    pattern: &'p Value,
    regex: Regex,
    unicode: bool,
}

impl Case<'_> {
    fn check(&self, tally: &mut Tally, method: &'static str, text: &str, expected: &Value, actual: Value) {
        *tally.checks.entry(method).or_default() += 1;
        let astral = !self.unicode && text.chars().any(|c| u32::from(c) > 0xffff);
        if expected.as_str() == Some(SURROGATE) {
            assert!(astral, "{method} of {} on {text:?} splits a surrogate pair in js", self.regex);
            tally.surrogate_skips += 1;
        } else if *expected != actual {
            if astral {
                tally.astral_differences += 1;
            } else {
                tally.failures.push(format!("{method} of {} on {text:?}: js {expected}, here {actual}", self.regex));
            }
        }
    }
}

fn exec_value(text: &str, m: Option<&Match>, expected: &Value) -> Value {
    let Some(m) = m else { return Value::Null };
    let mut value = vec![json!(utf16_index(text, m.start()))];
    value.extend((0..=m.group_count()).map(|index| m.group(index).map_or(Value::Null, |range| json!(&text[range]))));
    if let Some(Value::Object(names)) = expected.as_array().and_then(|expected| expected.last()) {
        let named: Map<String, Value> = names
            .keys()
            .map(|name| (name.clone(), m.named_group(name).map_or(Value::Null, |range| json!(&text[range]))))
            .collect();
        value.push(Value::Object(named));
    }
    Value::Array(value)
}

fn pieces(parts: Vec<Option<&str>>) -> Value {
    parts.into_iter().map(|part| part.map_or(Value::Null, |part| json!(part))).collect()
}

fn function_replacement(text: &str, m: &Match) -> String {
    let groups = (1..=m.group_count()).map(|index| m.group(index).map_or("~", |range| &text[range]));
    let parts: Vec<String> = std::iter::once(&text[m.range()])
        .chain(groups)
        .map(str::to_owned)
        .chain([utf16_index(text, m.start()).to_string()])
        .collect();
    format!("<{}>", parts.join("|"))
}

fn sparse(results: &Value, index: usize) -> Option<&Value> {
    results.get(index.to_string())
}

#[test]
fn matches_like_v8() {
    let fixture: Value =
        serde_json::from_str(include_str!("fixtures/js_parity.json")).expect("the fixture is generated by gen.mjs");
    let strings: Vec<&str> = fixture["strings"].as_array().unwrap().iter().map(|text| text.as_str().unwrap()).collect();
    let mut tally = Tally::default();
    let mut compiled = 0;
    for pattern in fixture["patterns"].as_array().unwrap() {
        let (source, flags) = (pattern["source"].as_str().unwrap(), pattern["flags"].as_str().unwrap());
        let regex = Regex::new(source, flags);
        if let Some(error) = pattern.get("error") {
            assert!(regex.is_err(), "/{source}/{flags} compiles, js rejects it: {error}");
            continue;
        }
        let regex = regex.unwrap_or_else(|error| panic!("{error}"));
        compiled += 1;
        let case = Case { pattern, regex, unicode: flags.contains('u') || flags.contains('v') };
        let texts = &strings[..usize::try_from(pattern["texts"].as_u64().unwrap()).unwrap()];
        for (index, &text) in texts.iter().enumerate() {
            check_text(&case, &mut tally, index, text);
        }
        for at in case.pattern["execAt"].as_array().unwrap() {
            let text = strings[usize::try_from(at[0].as_u64().unwrap()).unwrap()];
            let start = byte_index(text, usize::try_from(at[1].as_u64().unwrap()).unwrap());
            let actual = exec_value(text, case.regex.find_at(text, start).as_ref(), &at[2]);
            case.check(&mut tally, "find_at", text, &at[2], actual);
        }
    }
    println!(
        "{compiled} patterns, checks {:?}, {} differences and {} skipped surrogate halves on astral texts without u",
        tally.checks, tally.astral_differences, tally.surrogate_skips
    );
    assert!(
        tally.failures.is_empty(),
        "{} differences:\n{}",
        tally.failures.len(),
        tally.failures[..20.min(tally.failures.len())].join("\n")
    );
}

fn check_text(case: &Case<'_>, tally: &mut Tally, index: usize, text: &str) {
    let (pattern, regex) = (case.pattern, &case.regex);
    let expected = sparse(&pattern["exec"], index).cloned().unwrap_or(Value::Null);
    let found = regex.find(text);
    case.check(tally, "find", text, &expected, exec_value(text, found.as_ref(), &expected));
    if expected.as_str() != Some(SURROGATE) {
        case.check(tally, "is_match", text, &json!(!expected.is_null()), json!(regex.is_match(text)));
        case.check(tally, "search", text, &expected.get(0).cloned().unwrap_or(Value::Null), json!(regex.search(text)));
    }

    let expected = sparse(&pattern["all"], index).cloned().unwrap_or(json!([]));
    let actual: Vec<Value> = match expected.as_array() {
        Some(all) => regex
            .find_iter(text)
            .enumerate()
            .map(|(position, m)| exec_value(text, Some(&m), all.get(position).unwrap_or(&Value::Null)))
            .collect(),
        None => Vec::new(),
    };
    case.check(tally, "find_iter", text, &expected, Value::Array(actual));

    for (position, replacement) in pattern["replacements"].as_array().unwrap().iter().enumerate() {
        let expected = sparse(&pattern["replace"][position], index).cloned().unwrap_or_else(|| json!(text));
        let actual = regex.replace(text, replacement.as_str().unwrap());
        case.check(tally, "replace", text, &expected, json!(actual));
    }
    for (position, replacement) in pattern["replacementsAll"].as_array().unwrap().iter().enumerate() {
        let expected = sparse(&pattern["replaceAll"][position], index).cloned().unwrap_or_else(|| json!(text));
        let actual = regex.replace_all(text, replacement.as_str().unwrap());
        case.check(tally, "replace_all", text, &expected, json!(actual));
    }
    if pattern["origin"] == "core" {
        let expected = sparse(&pattern["replaceFn"], index).cloned().unwrap_or_else(|| json!(text));
        let actual = regex.replace_with(text, |m| function_replacement(text, m));
        case.check(tally, "replace_with", text, &expected, json!(actual));
        let expected = sparse(&pattern["replaceAllFn"], index).cloned().unwrap_or_else(|| json!(text));
        let actual = regex.replace_all_with(text, |m| function_replacement(text, m));
        case.check(tally, "replace_all_with", text, &expected, json!(actual));
        let expected = sparse(&pattern["split"], index).cloned().unwrap_or_else(|| json!([text]));
        case.check(tally, "split", text, &expected, pieces(regex.split(text)));
        let expected = sparse(&pattern["splitLimit"], index).cloned().unwrap_or_else(|| json!([text]));
        case.check(tally, "split_limit", text, &expected, pieces(regex.split_limit(text, 2)));
    }
}
